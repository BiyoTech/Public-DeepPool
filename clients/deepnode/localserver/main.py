def _parse_cli_args() -> argparse.Namespace:
    """Parse CLI arguments, supporting standalone run mode."""
    parser = argparse.ArgumentParser(
        description="DeepNode Local Worker — inference node local service",
    )
    parser.add_argument(
        "--config", "-c",
        type=str,
        default=None,
        help="Config file path (default: localserver/config.yaml)",
    )
    parser.add_argument(
        "--standalone",
        action="store_true",
        default=False,
        help="Enable standalone mode (auto-generate simei + auto-init)",
    )
    parser.add_argument(
        "--token", "-t",
        type=str,
        default=None,
        help="Platform auth token (overrides standalone.token in config)",
    )
    parser.add_argument(
        "--account", "-a",
        type=str,
        default=None,
        help="Platform login account (overrides standalone.account in config)",
    )
    parser.add_argument(
        "--password", "-p",
        type=str,
        default=None,
        help="Platform login password (overrides standalone.password in config)",
    )
    # Use parse_known_args to ignore unknown args injected by PyInstaller bootloader (-B -S -I)
    args, _ = parser.parse_known_args()
    return args


